from manim import *

myChemTemplate = TexTemplate(
                    tex_compiler="latex",   
                    output_format='.dvi',
                    preamble=r"""
                        \usepackage{amsmath}
                        \usepackage{amssymb}
                        \usepackage{chemfig}
                        \usepackage{mathtools}
                        \setchemfig{atom sep=2em,angle increment=45,bond offset=2pt,double bond sep=2pt}
                    """
                    )

timex: int = 1

siz: int = 0.6

class FermentationToAcetate(Scene):
    def construct(self):
        # Load images generated by Chemfig

        title = Tex(
            r"Äädikhappe käärimine",
            tex_template=myChemTemplate
        ).scale(siz*2).set_stroke(width=2)

        title.shift(UP * 3.3)

        glucose = Tex(
            r"""\chemname{\chemfig{OH-[:240,,1]>[:300]-O-[:300](<:[,,,1]OH)-[:240](<:[:300,,,1]OH)%
            -[:180](<[:240,,,2]HO)-[:120](-[:60])<:[:180,,,2]HO}}{Glükoos}""",
            tex_template=myChemTemplate
        ).scale(1).set_stroke(width=2)

        pyruvate = Tex(
            r"\chemname{\chemfig{-[:120](=[:60]O)-[:180](=[:240]O)-[:120]^{-}O}}{Püruvaat}",
            tex_template=myChemTemplate
        ).scale(siz).set_stroke(width=2)

        acetylCoA = Tex(
            r"\chemname{\chemfig{-[:-60](=[:-120]O)-S-[:-60]CoA}}{Atsetüül-CoA}",
            tex_template=myChemTemplate
        ).scale(siz).set_stroke(width=2)

        acetylphosphate = Tex(
            r"\chemname{\chemfig{-[:-60](=[:-120]O)-P(=[:90]O)(-[:-90]O^{-})-O^{-}}}{Atsetüülfosfaat}",
            tex_template=myChemTemplate
        ).scale(siz).set_stroke(width=2)

        acetate = Tex(
            r"\chemname{\chemfig{-[:180](=[:240]O)-[:120]O^{-}}}{Atsetaat}",
            tex_template=myChemTemplate
        ).scale(siz).set_stroke(width=2)

        CoA = Tex(
            r"+ \chemname{\chemfig{S-CoA}}{Koensüüm A}",
            tex_template=myChemTemplate
        ).scale(siz).set_stroke(width=2)

        CoA1 = Tex(
            r"\chemname{\chemfig{S-CoA}}{Koensüüm A}",
            tex_template=myChemTemplate
        ).scale(siz).set_stroke(width=2)

        co2 = Tex(
            r"\chemname{\chemfig{O=C=O}}{Süsinikdioksiid}",
            tex_template=myChemTemplate
        ).scale(siz).set_stroke(width=2)

        pluss = MathTex(
            r"+",
            tex_template=myChemTemplate
        ).scale(siz).set_stroke(width=2)

        basicarrow1 = MathTex(r"\xrightarrow[\text{Glükolüüs}]{2\:\text{ATP}\:\rightarrow\:4\:\text{ATP}}",tex_template=myChemTemplate).scale(0.8).set_stroke(width=2)
        basicarrow2 = MathTex(r"\xrightarrow[\text{Püruvaadi dehüdrogenaas}]{}",tex_template=myChemTemplate).scale(0.8).set_stroke(width=2)
        basicarrow3 = MathTex(r"\xrightarrow[\text{Fosfaadi atsetüültransferaas}]{\text{ATP} \:\rightarrow\: \text{ADP + P}_i}",tex_template=myChemTemplate).scale(0.8).set_stroke(width=2)
        basicarrow4 = MathTex(r"\xrightarrow[\text{Atsetaadi kinaas}]{\text{ADP + P}_i \:\rightarrow\: \text{ATP}}",tex_template=myChemTemplate).scale(0.8).set_stroke(width=2)

        self.play(Write(title), Write(glucose), run_time=timex)
        self.play(glucose.animate.scale(siz), run_time=timex/2)
        self.play(glucose.animate.shift(LEFT * 4), run_time=timex/2)
        self.play(Write(basicarrow1), run_time=timex)

        pyruvate.shift(RIGHT * 4)

        self.play(Write(pyruvate), run_time=timex)

        self.wait(2)

        self.play(Unwrite(glucose), run_time=timex/3)
        self.play(Unwrite(basicarrow1), run_time=timex/3)
        self.play(pyruvate.animate.shift(LEFT * 9), run_time=timex/2)

        acetylCoA.shift(RIGHT * 4)
        acetylCoA.shift(UP * 1.5)
        pluss.shift(RIGHT * 4)
        co2.shift(RIGHT * 4)
        co2.shift(DOWN * 1)
        CoA.shift(LEFT * 3)

        self.play(Write(CoA), run_time=timex/2)
        self.play(Write(basicarrow2), run_time=timex)
        self.play(Write(acetylCoA), run_time=timex)
        self.play(Write(pluss), run_time=timex/4)
        self.play(Write(co2), run_time=timex)   

        self.wait(2)

        self.play(Unwrite(pyruvate), run_time=timex/3)
        self.play(Unwrite(CoA), run_time=timex/6)
        self.play(Unwrite(basicarrow2), run_time=timex/3)
        self.play(Unwrite(pluss), run_time=timex/6)
        self.play(Unwrite(co2), run_time=timex/3)
        self.play(acetylCoA.animate.shift(LEFT * 8), run_time=timex/2)
        self.play(acetylCoA.animate.shift(DOWN * 1.5), run_time=timex/2)

        pluss = MathTex(
            r"+",
            tex_template=myChemTemplate
        ).scale(siz).set_stroke(width=2)

        acetylphosphate.shift(RIGHT * 4)
        acetylphosphate.shift(UP * 1.5)
        pluss.shift(RIGHT * 4)
        CoA1.shift(RIGHT * 4)
        CoA1.shift(DOWN * 1)

        self.play(Write(basicarrow3), run_time=timex)
        self.play(Write(acetylphosphate), run_time=timex)
        self.play(Write(pluss), run_time=timex/2)
        self.play(Write(CoA1), run_time=timex)

        self.wait(2)

        self.play(Unwrite(acetylCoA), run_time=timex/3)
        self.play(Unwrite(basicarrow3), run_time=timex/3)
        self.play(Unwrite(pluss), run_time=timex/6)
        self.play(Unwrite(CoA1), run_time=timex/3)

        self.play(acetylphosphate.animate.shift(LEFT * 8), run_time=timex/2)
        self.play(acetylphosphate.animate.shift(DOWN * 1.5), run_time=timex/2)

        acetate.shift(RIGHT * 4)

        self.play(Write(basicarrow4), run_time=timex)
        self.play(Write(acetate), run_time=timex)

        self.wait(2)

        self.play(Unwrite(acetylphosphate), run_time=timex/3)
        self.play(Unwrite(basicarrow4), run_time=timex/3)

        self.play(acetate.animate.shift(LEFT * 4), run_time=timex/2)
        self.play(acetate.animate.scale(3), run_time=timex/2)

        self.wait(0.1)
